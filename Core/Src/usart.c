static uint8_t uart_rx_byte;
static uint8_t cmd_buf[32];
static uint8_t cmd_idx = 0;

extern osMessageQueueId_t Queue_UART_RXHandle;

void USART_StartReceiveIT(void)
{
    HAL_UART_Receive_IT(&huart1, &uart_rx_byte, 1);
}

void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == USART1)
    {
        /* Echo each received byte directly via TX register for debug */
        while (!(USART1->ISR & USART_ISR_TXE_TXFNF));
        USART1->TDR = uart_rx_byte;

        if (uart_rx_byte == '\n' || uart_rx_byte == '\r')
        {
            if (cmd_idx > 0)
            {
                cmd_buf[cmd_idx] = '\0';
                osMessageQueuePut(Queue_UART_RXHandle, cmd_buf, 0, 0);
                memset(cmd_buf, 0, sizeof(cmd_buf));
                cmd_idx = 0;
            }
        }
        else if (cmd_idx < 31)
        {
            cmd_buf[cmd_idx++] = uart_rx_byte;
        }
        
        HAL_UART_Receive_IT(&huart1, &uart_rx_byte, 1);
    }
}

